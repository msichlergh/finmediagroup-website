/**
 * One-shot port helper. Generates app/port.css: the small additive layer the
 * Next.js port needs on top of the verbatim brand.css.
 *
 * The bulk of it is font plumbing. brand.css names the families literally
 * ("Prompt" / "Montserrat") because the legacy site pulled them from the Google
 * Fonts CDN. next/font self-hosts them under generated family names exposed as
 * CSS variables, so every rule that named a family literally is re-emitted here
 * pointing at the variable instead. brand.css itself stays byte-identical to the
 * original, which keeps it diffable against the legacy site.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const VARS = { Prompt: 'var(--font-prompt)', Montserrat: 'var(--font-montserrat)' }

/** Pull `selector { ... font-family: 'X' ... }` pairs out of a stylesheet. */
function collect(css, sourceLabel) {
  const rules = []
  // naive but sufficient: these stylesheets have no nested at-rule braces
  // around the font declarations we care about
  const re = /([^{}]+)\{([^{}]*)\}/g
  let m
  while ((m = re.exec(css))) {
    const selector = m[1].trim()
    const body = m[2]
    if (selector.startsWith('@')) continue

    const fm = body.match(/font-family\s*:\s*([^;]+)/i)
    if (!fm) continue

    const value = fm[1].trim()
    const family = Object.keys(VARS).find((f) =>
      new RegExp(`['"]${f}['"]`).test(value)
    )
    if (!family) continue

    // preserve any fallback that followed the literal family
    const rest = value
      .split(',')
      .slice(1)
      .map((s) => s.trim())
      .filter(Boolean)

    rules.push({
      selector,
      value: [VARS[family], ...rest].join(', '),
      source: sourceLabel,
    })
  }
  return rules
}

const globals = readFileSync(join(root, 'app', 'globals.css'), 'utf8')
const home = readFileSync(join(root, 'app', 'home.css'), 'utf8')

const rules = [...collect(globals, 'globals.css'), ...collect(home, 'home.css')]

const fontBlock = rules
  .map((r) => `${r.selector} { font-family: ${r.value} }`)
  .join('\n')

writeFileSync(
  join(root, 'app', 'port.css'),
  `/* GENERATED by scripts/gen-port-css.mjs — additive layer for the Next.js port.
   Loaded after globals.css and home.css so these declarations win.
   Edit the generator, not this file. */

/* --- next/font wiring -------------------------------------------------------
   brand.css names 'Prompt' and 'Montserrat' literally (they came from the
   Google Fonts CDN). next/font self-hosts them under generated names, so each
   of those ${rules.length} rules is repointed at the CSS variable here. */
${fontBlock}

/* --- markup differences -----------------------------------------------------
   The burger is a <button> now rather than a <div>, for keyboard and screen
   reader support. Strip the UA button chrome so it renders as it did before. */
.nav-burger {
  background: none;
  border: 0;
  padding: 0;
  font: inherit;
  color: inherit;
  -webkit-appearance: none;
  appearance: none;
}

/* --- motion preferences -----------------------------------------------------
   The legacy site animated unconditionally. The React components skip their
   JS-driven animations under prefers-reduced-motion; this covers the pure-CSS
   ones. */
@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation-duration: .01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: .01ms !important;
    scroll-behavior: auto !important;
  }
  .reveal { opacity: 1; transform: none }
}
`
)

console.log(`app/port.css — ${rules.length} font rules repointed at next/font variables`)
for (const r of rules) console.log(`  ${r.source.padEnd(12)} ${r.selector}`)
